/**
 * Os anúncios de exemplo, prontos para trocar por API.
 *
 * É conteúdo FICTÍCIO: os telefones usam o prefixo `5597999990` de propósito
 * (o mock nunca deve mandar ninguém a um número real) e os donos são nomes
 * genéricos. O preço é sempre o valor total do aluguel; o que está incluso
 * (água, luz, internet) vem separado em `costs`, para o card dizer a verdade
 * antes de o visitante abrir o anúncio, como o QuintoAndar faz.
 *
 * As fotos não têm `url`: enquanto não chegarem fotos reais dos donos, o
 * frontend desenha cada ambiente como cena SVG. `url: null` é o contrato para
 * "ainda não há foto", e a troca por foto real não muda nenhuma tela.
 *
 * `owner.updatedAt` é o que o selo "atualizado há X dias" lê: anúncio parado é
 * o sinal de golpe e de imóvel já alugado, os dois defeitos que fizeram o
 * grupo de WhatsApp deixar de servir.
 */
function photos(count: number): Listing['photos'] {
  const order = [
    PHOTO_ENVIRONMENT.FACADE,
    PHOTO_ENVIRONMENT.BEDROOM,
    PHOTO_ENVIRONMENT.BATHROOM,
    PHOTO_ENVIRONMENT.KITCHEN,
    PHOTO_ENVIRONMENT.LIVING,
  ]
  return order.slice(0, count).map((environment, index) => ({
    id: `${environment.toLowerCase()}-${index}`,
    environment,
    url: null,
  }))
}

