import {
  UPLOAD_STATUS,
  left,
  right,
  type Either,
  type StorageMimetype,
  type UploadStatus,
} from '@aporta/shared'

import type {
  StorageContentMismatch,
  StorageNotPending,
  StorageSizeMismatch,
} from './storage.errors.ts'

import FileSignature from '#domain/shared/file-signature.value-object'

/** What the bucket holds, as far as the type of the object is concerned. */
export type StorageContent = {
  /** The `Content-Type` of the stored object. */
  readonly contentType: string | undefined
  /** The first `FileSignature.LENGTH` bytes of the object. */
  readonly head: Uint8Array
}

/**
 * The file state: the `storages` row that describes a bucket object.
 * The binary does not pass through the application; what lives here is the metadata and the
 * upload cycle (`PENDING` → `UPLOADED`, or cancelled).
 *
 * `ownerId` is the account that opened the upload (the `actor` of the `create`): there is no
 * anonymous upload (`_standards/backend.md` §5.4). It is recorded, and authorizes nothing by
 * itself - the file is a shared record, attached by whoever uses it.
 *
 * `path` is the bucket key, generated by `StorageContract.key`, and never derives
 * from the name the user sent (`originalName` is only a label).
 */
export type StorageProps = {
  readonly id: string
  readonly filename: string
  readonly originalName: string
  readonly mimetype: string
  readonly size: number
  readonly path: string
  readonly ownerId: string
  status: UploadStatus
  readonly partSize: number | null
  uploadId: string | null
  deletedAt: Date | null
}

/** What opening the upload records. */
export type StorageCreateInput = {
  readonly id: string
  readonly key: string
  readonly originalName: string
  readonly mimetype: StorageMimetype
  readonly size: number
  readonly partSize: number
  readonly uploadId: string | null
  /** The account that opens the upload: the `actor`. */
  readonly ownerId: string
}

/**
 * The file. Born `PENDING` and with an owner, the account that opened the upload; whoever
 * attaches it keeps the id. Only
 * confirmation, checking what actually got uploaded, makes it `UPLOADED`.
 */
export default class Storage {
  private constructor(private readonly props: StorageProps) {}

  static create(input: StorageCreateInput): Storage {
    return new Storage({
      id: input.id,
      filename: input.key,
      originalName: input.originalName,
      mimetype: input.mimetype,
      size: input.size,
      path: input.key,
      ownerId: input.ownerId,
      status: UPLOAD_STATUS.PENDING,
      partSize: input.partSize,
      uploadId: input.uploadId,
      deletedAt: null,
    })
  }

  /** Rehydration by the repository: the data already passed the invariants when it was saved. */
  static restore(props: StorageProps): Storage {
    return new Storage({ ...props })
  }

  /**
   * Closes the upload with the size the bucket says it received. If it diverged from the
   * declared one: refuses, and the row no longer describes anything. If it matched: `UPLOADED`, and the
   * `uploadId` is dropped, because the bucket has already closed that conversation.
   */
  confirm(received: number): Either<StorageSizeMismatch, Storage> {
    if (received !== this.props.size)
      return left({
        code: 'STORAGE_SIZE_MISMATCH',
        declared: this.props.size,
        received,
      })

    this.props.status = UPLOAD_STATUS.UPLOADED
    this.props.uploadId = null
    return right(this)
  }

  /**
   * Checks that what was stored is of the declared type, and not only that it has the declared
   * size: the `Content-Type` of the object and its first bytes (magic bytes) must both be the
   * `mimetype` the upload was opened with (`_standards/backend.md` §5.4). Changes nothing: the
   * caller decides what to do with a refused object (delete it, and the row).
   */
  verifyContent(
    content: StorageContent,
  ): Either<StorageContentMismatch, Storage> {
    const signature = FileSignature.create(content.head)

    if (signature.isLeft())
      return left({
        code: 'STORAGE_CONTENT_MISMATCH',
        declared: this.props.mimetype,
        detected: null,
      })

    const detected = signature.value.mimetype

    if (
      detected !== this.props.mimetype ||
      content.contentType !== this.props.mimetype
    )
      return left({
        code: 'STORAGE_CONTENT_MISMATCH',
        declared: this.props.mimetype,
        detected,
      })

    return right(this)
  }

  /**
   * Cancels the upload in progress. The row stays, marked, so a repeated
   * `DELETE` answers the same; whoever deletes it for good is `storages:prune`.
   */
  cancel(at: Date): Either<StorageNotPending, Storage> {
    if (this.props.status !== UPLOAD_STATUS.PENDING || this.props.deletedAt)
      return left({ code: 'STORAGE_NOT_PENDING' })

    this.props.deletedAt = at
    return right(this)
  }

  /** Confirmed: the binary is whole in the bucket. */
  isUploaded(): boolean {
    return this.props.status === UPLOAD_STATUS.UPLOADED
  }

  get id(): string {
    return this.props.id
  }

  snapshot(): Readonly<StorageProps> {
    return { ...this.props }
  }
}
