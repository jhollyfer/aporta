/**
 * Typed configuration of the `scripts/` guard-rails (`_standards/backend.md` §10,
 * `_standards/architecture.md` §6): every exception of any check lives here, each
 * one with a `reason`, and an unused exception fails the check.
 *
 * `temporaryExceptions` is the single visible point of the TEMPORARY exceptions of the
 * conformity work with the standard: each item is a deviation that the guard-rail already enforces and
 * that a later batch fixes. The list only shrinks; on reaching zero, the field goes away.
 */

/** An entry of `newAllowlist`. */
export type NewAllowlistEntry = {
  /** The symbol built with `new`. */
  readonly symbol: string
  /** Where the use lives. Accepts `**` and `*`. */
  readonly file: string
  /** Why that `new` is legitimate. */
  readonly reason: string
}

/** A route with a per-record rule that is not just ownership: the controller uses `ctx.bouncer` (§4.6). */
export type BouncerRequiredEntry = {
  readonly file: string
  readonly reason: string
}

/**
 * A known deviation that the conformity work with the standard will still fix. `check`
 * says which guard enforces it: `pattern-check` (rule + file pair) or `depcruise`
 * (importing file + imported file pair, read by `depcruise.config.ts`).
 */
export type TemporaryException = {
  readonly check: 'pattern-check' | 'depcruise'
  readonly rule: string
  readonly file: string
  /** `depcruise` only: the imported file. */
  readonly target?: string
  /** The conformity batch that fixes and removes the exception. */
  readonly batch: 4 | 5 | 6
  readonly reason: string
}

export type PatternCheckConfiguration = {
  readonly newAllowlist: ReadonlyArray<NewAllowlistEntry>
  readonly softDeleteExempt: ReadonlyArray<string>
  /** FORM files: same public API and structure, content per domain. */
  readonly shape: ReadonlyArray<string>
  readonly envOutsideCode: Readonly<Record<string, string>>
  readonly bouncerRequired: ReadonlyArray<BouncerRequiredEntry>
  readonly temporaryExceptions: ReadonlyArray<TemporaryException>
}

